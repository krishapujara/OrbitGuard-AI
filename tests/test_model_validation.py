def test_grouped_split_holds_out_candidates() -> None:
    rows = []
    for i in range(12):
        rows.append(
            {
                "candidate_id": f"c{i}",
                "target_epoch_utc": f"2019-12-0{(i % 9) + 1}T00:00:00+00:00",
                "x": i,
            }
        )
    frame = pd.DataFrame(rows)
    train, val, test, meta = chronological_group_split(frame, seed=0)
    assert_no_group_leakage(train, val, "candidate_id")
    assert_no_group_leakage(train, test, "candidate_id")
    assert_no_group_leakage(val, test, "candidate_id")
    assert meta["protocol"] == "grouped_chronological_holdout"
    assert len(train) + len(val) + len(test) == len(frame)


def test_split_rejects_too_few_groups() -> None:
    frame = pd.DataFrame(
        {
            "candidate_id": ["a", "b"],
            "target_epoch_utc": ["2019-01-01T00:00:00+00:00"] * 2,
        }
    )
    with pytest.raises(ValueError, match="at least 6"):
        chronological_group_split(frame)


def test_classification_report_metrics() -> None:
    y_true = [0, 0, 1, 1, 1]
    y_pred = [0, 1, 1, 1, 0]
    y_score = [0.1, 0.6, 0.8, 0.9, 0.4]

    report = classification_report_dict(y_true, y_pred, y_score)
    assert report["n"] == 5
    assert report["prevalence_positive"] == 0.6
    assert 0.0 <= report["accuracy"] <= 1.0
    assert 0.0 <= report["precision"] <= 1.0
    assert 0.0 <= report["recall"] <= 1.0
    assert 0.0 <= report["f1"] <= 1.0
    assert report["roc_auc"] is not None
    assert report["pr_auc"] is not None
    assert report["brier"] is not None
    assert "Accuracy is misleading for rare-event labels" in report["accuracy_note"]


def test_majority_baseline_predicts_most_frequent() -> None:
    y_true = np.array([0, 1, 1, 1, 1])
    baseline = majority_baseline(y_true)
    assert np.all(baseline == 1)

    y_true_zeros = np.array([0, 0, 0, 1])
    baseline_zeros = majority_baseline(y_true_zeros)
    assert np.all(baseline_zeros == 0)


def test_prediction_service_rejects_untrusted_origin(tmp_path) -> None:
    import joblib

    model_path = tmp_path / "baseline_model.joblib"
    meta_path = tmp_path / "baseline_model.meta.json"

    # Save a fake pipeline and untrusted metadata
    joblib.dump({"pipeline": "dummy"}, model_path)
    meta = {
        "model_type": "LogisticRegression",
        "target_definition": "below_threshold_proxy",
        "feature_schema": FEATURE_COLUMNS,
        "training_timestamp": "2026-10-14T00:00:00Z",
        "trusted_origin": "untrusted-external-source",
    }
    meta_path.write_text(json.dumps(meta), encoding="utf-8")

    service = ModelPredictionService(artifact_dir=tmp_path)
    with pytest.raises(IncompatibleModelError, match="Refusing to load a model that was not generated by this project"):
        service.load()

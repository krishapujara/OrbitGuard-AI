"""Load trusted local model artifacts and apply them to screening features."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from backend.exceptions import IncompatibleModelError, ModelUnavailableError
from backend.feature_engineering import FEATURE_COLUMNS
from config.settings import get_settings

REQUIRED_META = {
    "model_type",
    "target_definition",
    "feature_schema",
    "training_timestamp",
}


class ModelPredictionService:
    def __init__(self, artifact_dir: Path | None = None) -> None:
        self._custom_dir = artifact_dir is not None
        self.artifact_dir = artifact_dir or get_settings().ml_artifacts

    def artifact_paths(self) -> tuple[Path, Path]:
        p = self.artifact_dir / "baseline_model.joblib"
        m = self.artifact_dir / "baseline_model.meta.json"
        if p.exists() and m.exists():
            return p, m
        if not self._custom_dir:
            fallback = get_settings().project_root / "models" / "artifacts"
            if (fallback / "baseline_model.joblib").exists():
                return fallback / "baseline_model.joblib", fallback / "baseline_model.meta.json"
        return p, m

    def available(self) -> bool:
        model_path, meta_path = self.artifact_paths()
        return model_path.exists() and meta_path.exists()

    def load(self) -> tuple[Any, dict]:
        model_path, meta_path = self.artifact_paths()
        if not self.available():
            raise ModelUnavailableError(
                "No trusted local model artifact was found. Run "
                "`python -m ml.train_baseline` after a catalog snapshot is available. "
                "Physical SGP4 screening continues without ML."
            )
        try:
            bundle = joblib.load(model_path)
            meta = _read_meta(meta_path)
        except Exception as exc:
            raise IncompatibleModelError("Model artifact could not be read as a trusted joblib bundle.") from exc
        if not isinstance(bundle, dict) or "pipeline" not in bundle:
            raise IncompatibleModelError("Model artifact is missing the pipeline object.")
        missing = REQUIRED_META - set(meta)
        if missing:
            raise IncompatibleModelError(f"Model metadata missing fields: {sorted(missing)}")
        if meta.get("trusted_origin") != "orbitalguard-ai-local":
            raise IncompatibleModelError("Refusing to load a model that was not generated by this project.")
        schema = list(meta.get("feature_schema") or [])
        if schema != FEATURE_COLUMNS:
            raise IncompatibleModelError("Model feature schema does not match the current application.")
        return bundle["pipeline"], meta

    def predict_rows(self, frame: pd.DataFrame) -> pd.DataFrame:
        pipeline, meta = self.load()
        X = frame[FEATURE_COLUMNS]
        out = frame.copy()
        if hasattr(pipeline, "predict_proba"):
            proba = pipeline.predict_proba(X)
            positive = proba[:, 1] if proba.ndim == 2 and proba.shape[1] > 1 else proba.ravel()
            out["ml_proxy_score"] = positive
            out["ml_proxy_label"] = (positive >= 0.5).astype(int)
        else:
            pred = pipeline.predict(X)
            out["ml_proxy_score"] = pred
            out["ml_proxy_label"] = pred
        out["ml_target_name"] = meta.get("target_definition")
        out["ml_is_collision_probability"] = False
        return out

    def status(self) -> dict:
        if not self.available():
            return {"available": False, "reason": "No local baseline_model.joblib artifact."}
        try:
            _, meta = self.load()
        except (ModelUnavailableError, IncompatibleModelError) as exc:
            return {"available": False, "reason": str(exc)}
        return {"available": True, "meta": meta}


def _read_meta(path: Path) -> dict:
    import json

    return json.loads(path.read_text(encoding="utf-8"))
